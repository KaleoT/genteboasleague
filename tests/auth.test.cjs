const {test}=require('node:test');
const assert=require('node:assert/strict');
const jwt=require('jsonwebtoken');
const bcrypt=require('bcryptjs');
const {createApp}=require('./approved-fixture.cjs');
const secret='test-only-secret-'.repeat(4);
test('REST authentication, relational constraints and authorization',async t=>{
 const {app,db}=createApp({database:':memory:',secret,rateLimit:1000});
 const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
 t.after(()=>{server.close();db.close();});
 const base='http://127.0.0.1:'+server.address().port;
 const call=async(url,body,token,method)=>{const r=await fetch(base+url,{method:method || (body?'POST':'GET'),headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,data:r.status===204?null:await r.json()};};
 const payload={name:'Jogador',email:'PLAYER@Example.com',phone:'(35) 99999-9999',password:'uma-senha-segura',team_id:'sq15',role:'admin'};
 assert.equal((await call('/api/teams/available')).data.length,17);
 assert.equal((await call('/api/auth/me')).status,401);
 assert.equal((await call('/api/auth/register',{...payload,email:'invalid'})).status,400);
 assert.equal((await call('/api/auth/register',{...payload,password:'short'})).status,400);
 const registered=await call('/api/auth/register',payload);assert.equal(registered.status,201);
 const token=registered.data.access_token;
 assert.equal(registered.data.user.role,'player');assert.equal(registered.data.user.email,'player@example.com');assert.equal(registered.data.user.phone,'35999999999');
 assert.equal(registered.data.user.hashed_password,undefined);
 assert.ok(await bcrypt.compare(payload.password,db.prepare('SELECT hashed_password FROM users').get().hashed_password));
 assert.equal((await call('/api/teams/available')).data.some(t=>t.id==='sq15'),false);
 for(const identifier of ['PLAYER@example.com','+55 (35) 99999-9999']) assert.equal((await call('/api/auth/login',{identifier,password:payload.password})).status,200);
 assert.equal((await call('/api/auth/login',{identifier:payload.email,password:'wrong'})).status,401);
 assert.equal((await call('/api/auth/me',null,token)).data.team.id,'sq15');
 assert.equal((await call('/api/admin/users',null,token)).status,403);
 assert.equal((await call('/api/auth/register',{...payload,team_id:'sq16',phone:'35999999998'})).status,409);
 assert.equal((await call('/api/auth/register',{...payload,team_id:'sq16',email:'other@example.com'})).status,409);
 assert.equal((await call('/api/auth/register',{...payload,team_id:'sq15',email:'other@example.com',phone:'35999999998'})).status,409);
 const races=await Promise.all([1,2].map(i=>call('/api/auth/register',{...payload,team_id:'sq17',email:`race${i}@example.com`,phone:`3599999999${i}`})));
 assert.deepEqual(races.map(r=>r.status).sort(),[201,409]);
 assert.equal(db.prepare("SELECT count(*) AS n FROM users WHERE team_id='sq17'").get().n,1);
 assert.throws(()=>db.prepare("INSERT INTO users(id,name,email,phone,hashed_password,team_id) VALUES('bad','bad','bad@example.com','35988888888','bad','missing')").run(),/FOREIGN KEY/);
 const expired=jwt.sign({role:'admin'},secret,{subject:registered.data.user.id,expiresIn:-1,issuer:'gbl-api',audience:'gbl-web'});
 assert.equal((await call('/api/auth/me',null,expired)).status,401);
 assert.equal((await call('/api/auth/me',null,token.slice(0,-8)+'tampered')).status,401);
 db.prepare("UPDATE users SET role='admin' WHERE id=?").run(registered.data.user.id);
 assert.equal((await call('/api/admin/users',null,token)).status,200);
 assert.equal((await call('/api/auth/logout',{},token)).status,204);
 assert.equal((await call('/api/auth/me',null,token)).status,401);
 for(const url of ['/.env','/data/gbl.sqlite','/server/app.cjs','/node_modules/express/package.json']) assert.equal((await fetch(base+url)).status,404);
 const cors=await fetch(base+'/api/teams/available',{headers:{Origin:'https://evil.example'}});assert.equal(cors.headers.get('access-control-allow-origin'),null);
});
